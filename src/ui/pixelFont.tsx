const cache = new Map<string, { d: string; w: number }>();
/** SVG path (1 unit = 1 font pixel) for a line of text; 1 pixel of spacing between letters. */
export function pixelPath(text: string): { d: string; w: number } {
  const key = text.toUpperCase();
  const hit = cache.get(key);
  if (hit) return hit;
  let d = '', x = 0;
  for (const ch of key) {
    const g = G[ch] ?? G['?'];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '#') d += `M${x + c} ${r}h1v1h-1z`;
    x += 6;
  }
  const out = { d, w: Math.max(1, x - 1) };
  cache.set(key, out);
  return out;
}

/** Text in the pixel font. `px` = screen pixels per font pixel; optional hard drop shadow. */
export function PixelText({ text, px = 4, shadow = true, class: cls = '' }: { text: string; px?: number; shadow?: boolean; class?: string }) {
  const { d, w } = pixelPath(text);
  return (
    <svg class={'pixeltext ' + cls} role="img" aria-label={text} width={(w + (shadow ? 1 : 0)) * px} height={(7 + (shadow ? 1 : 0)) * px}
      viewBox={`0 0 ${w + (shadow ? 1 : 0)} ${7 + (shadow ? 1 : 0)}`} shape-rendering="crispEdges">
      {shadow && <path d={d} transform="translate(1 1)" class="pt-shadow" />}
      <path d={d} class="pt-fill" />
    </svg>
  );
}
